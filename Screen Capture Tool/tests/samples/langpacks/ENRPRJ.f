C     ENROLLMENT PROJECTION MODEL (1987)
      PROGRAM ENRPRJ
      COMMON /RATES/ BIRTH(50), MIGR(50)
      DIMENSION ENR(13,50)
      OPEN(UNIT=10, FILE='ENROLL.DAT', STATUS='OLD')
      DO 100 I = 1, 50
         READ(10,*) (ENR(J,I), J=1,13)
         CALL PROJ(ENR, I)
  100 CONTINUE
      IF (ENR(1,1)) 200, 200, 300
  200 GO TO 900
  300 WRITE(*,*) 'OK'
  900 STOP
      END
      SUBROUTINE PROJ(E, K)
      DIMENSION E(13,50)
      E(1,K) = E(1,K) * 1.01
      RETURN
      END
