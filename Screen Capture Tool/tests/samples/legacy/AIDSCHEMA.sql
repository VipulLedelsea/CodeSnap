-- DB2 schema for school aid
CREATE TABLE MDE.DISTRICT (
    DISTRICT_ID     CHAR(6)        NOT NULL,
    DISTRICT_NAME   VARCHAR(80)    NOT NULL,
    COUNTY_CODE     CHAR(3),
    PRIMARY KEY (DISTRICT_ID)
) IN AIDTS01;

CREATE TABLE MDE.DISTRICT_AID (
    DISTRICT_ID     CHAR(6)        NOT NULL REFERENCES MDE.DISTRICT (DISTRICT_ID),
    FISCAL_YEAR     SMALLINT       NOT NULL,
    STUDENT_COUNT   INTEGER,
    TOTAL_AMOUNT    DECIMAL(13,2)  DEFAULT 0,
    CONSTRAINT PK_AID PRIMARY KEY (DISTRICT_ID, FISCAL_YEAR)
) IN AIDTS01 CCSID EBCDIC;

CREATE INDEX MDE.IX_AID_YEAR ON MDE.DISTRICT_AID (FISCAL_YEAR);

CREATE VIEW MDE.V_AID_SUMMARY AS
    SELECT D.DISTRICT_NAME, A.TOTAL_AMOUNT
    FROM MDE.DISTRICT_AID A JOIN MDE.DISTRICT D ON D.DISTRICT_ID = A.DISTRICT_ID;
