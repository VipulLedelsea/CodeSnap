from pathlib import Path

def fixed(spec, seq=True):
    out, n = [], 0
    for raw in spec.strip("\n").split("\n"):
        tag, _, text = raw.partition("|")
        n += 100
        s = f"{n:06d}" if seq else "      "
        if tag == "*":
            out.append(f"{s}*{text}")
        elif tag == "A":
            out.append(f"{s} {text}")
        elif tag == "B":
            out.append(f"{s}     {text}")
        elif tag == "-":
            out.append(f"{s}-    {text}")
        elif tag == "":
            out.append("")
    return "\n".join(l.rstrip() for l in out) + "\n"

